-- USER_SETTINGS 表：存储用户个人设置
CREATE TABLE IF NOT EXISTS USER_SETTINGS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    USER_ID BIGINT NOT NULL UNIQUE,
    THEME_MODE VARCHAR(20) NOT NULL DEFAULT 'light',
    NOTIFY_ON_COMPLETE BOOLEAN NOT NULL DEFAULT TRUE,
    LANGUAGE VARCHAR(10) DEFAULT 'zh-CN',
    PAGE_SIZE INT DEFAULT 20,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

-- ORG_CONFIG 表：存储组织级别的配置信息
CREATE TABLE IF NOT EXISTS ORG_CONFIG (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    ORGANIZATION_ID BIGINT NOT NULL UNIQUE,
    DEFAULT_BROWSER VARCHAR(20) NOT NULL DEFAULT 'chrome',
    DRIVER_MODE VARCHAR(20) NOT NULL DEFAULT 'local',
    REMOTE_URL VARCHAR(255),
    STEP_TIMEOUT INT NOT NULL DEFAULT 30,
    SCREENSHOT_STRATEGY VARCHAR(20) NOT NULL DEFAULT 'on_failure',
    WINDOW_SIZE VARCHAR(20) NOT NULL DEFAULT '1920x1080',
    API_TIMEOUT INT NOT NULL DEFAULT 30000,
    PROXY_SERVER VARCHAR(255),
    SSL_VERIFY BOOLEAN NOT NULL DEFAULT TRUE,
    RETRY_COUNT INT NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATIONS(ID)
);
